// Builds src/games/trafficEscape/levels.js: a bank of Traffic Escape puzzles sorted easy → hard.
//   node scripts/gen-traffic-levels.mjs [seconds=180] [levels=60]
// Random layouts are explored completely; every position's distance to the nearest solve is measured
// (moves are reversible, so one BFS out of the solved states does it) and the farthest one is kept.
// Each kept puzzle's par is re-checked by the game's own solver before it is written.
import { writeFileSync } from 'node:fs'
import { EXIT_ROW, SIZE, cellsOf, decode, encode, isSolved, keyOf, movesFrom, occupancy, solve } from '../src/games/trafficEscape/logic.js'

const seconds = Number(process.argv[2] || 180)
const count = Number(process.argv[3] || 60)

let seed = 20261105
const rand = () => { // mulberry32: the bank is reproducible
  seed = (seed + 0x6d2b79f5) >>> 0
  let t = Math.imul(seed ^ (seed >>> 15), seed | 1)
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296
}
const int = (a, b) => a + Math.floor(rand() * (b - a + 1))

function randomLayout(nCars) {
  const p = { size: SIZE, exitRow: EXIT_ROW, cars: [{ len: 2, horiz: true, lane: EXIT_ROW }] }
  const state = [int(0, 3)]
  for (let attempt = 0; p.cars.length < nCars && attempt < 300; attempt++) {
    const len = rand() < 0.3 ? 3 : 2, horiz = rand() < 0.5, lane = int(0, SIZE - 1)
    if (horiz && lane === EXIT_ROW) continue // a second car in the exit row could never get out of the way
    const pos = int(0, SIZE - len)
    const grid = occupancy(p, state)
    p.cars.push({ len, horiz, lane })
    if (cellsOf(p, p.cars.length - 1, pos).some(c => grid[c])) { p.cars.pop(); continue }
    state.push(pos)
  }
  return { p, state }
}

function farthest(p, start, limit = 12000) {
  const states = [start], adj = []
  const index = new Map([[keyOf(start), 0]])
  for (let q = 0; q < states.length; q++) {
    const edges = []
    for (const [k, pos] of movesFrom(p, states[q])) {
      const next = states[q].slice(); next[k] = pos
      const key = keyOf(next)
      let j = index.get(key)
      if (j === undefined) {
        if (states.length >= limit) return null
        j = states.length; index.set(key, j); states.push(next)
      }
      edges.push(j)
    }
    adj.push(edges)
  }
  const dist = new Int32Array(states.length).fill(-1)
  const queue = []
  states.forEach((s, i) => { if (isSolved(p, s)) { dist[i] = 0; queue.push(i) } })
  for (let q = 0; q < queue.length; q++) for (const j of adj[queue[q]]) if (dist[j] < 0) { dist[j] = dist[queue[q]] + 1; queue.push(j) }
  let best = -1
  dist.forEach((d, i) => { if (d > 0 && (best < 0 || d > dist[best])) best = i })
  return best < 0 ? null : { state: states[best], par: dist[best] }
}

const found = new Map() // grid → par
const end = Date.now() + seconds * 1000
let tries = 0
while (Date.now() < end) {
  tries++
  const { p, state } = randomLayout(int(6, 13))
  const res = farthest(p, state)
  if (!res || res.par < 3) continue
  found.set(encode(p, res.state), res.par)
}
const byPar = new Map()
for (const [grid, par] of found) byPar.set(par, [...(byPar.get(par) || []), grid])
const pars = [...byPar.keys()].sort((a, b) => a - b)
console.log(`${tries} layouts, ${found.size} puzzles; pars:`, pars.map(k => `${k}×${byPar.get(k).length}`).join(' '))

// Pick `count` levels on a curve from easy to the hardest found; easy levels prefer fewer cars.
const carCount = g => new Set(g.replace(/\./g, '')).size
const maxPar = pars.at(-1)
const bank = []
for (let i = 0; i < count; i++) {
  const want = Math.round(3 + (maxPar - 3) * Math.pow(i / (count - 1), 1.25))
  let par = pars.reduce((a, b) => (Math.abs(b - want) < Math.abs(a - want) && byPar.get(b).length ? b : a), pars.find(k => byPar.get(k).length))
  const pool = byPar.get(par).sort((a, b) => (i < count / 3 ? carCount(a) - carCount(b) : carCount(b) - carCount(a)))
  const grid = pool.shift()
  const check = solve(decode(grid), decode(grid).start)
  if (!check || check.length !== par) throw new Error(`par mismatch for ${grid}`)
  bank.push([grid, par])
}
bank.sort((a, b) => a[1] - b[1])
writeFileSync(new URL('../src/games/trafficEscape/levels.js', import.meta.url),
  `// Generated by scripts/gen-traffic-levels.mjs (${tries} layouts searched): [grid, par] sorted easy → hard.\n` +
  `// Grid: 6×6 row by row, '.' empty, 'A' the red car (exit on the right of row 3), 'B'… other cars.\n` +
  `export const BANK = [\n${bank.map(([g, p]) => `  ['${g}', ${p}],`).join('\n')}\n]\n`)
console.log('pars written:', bank.map(b => b[1]).join(' '))
